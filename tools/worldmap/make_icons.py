#!/usr/bin/env python3
"""Generates MapIconNames.java: what each world map icon means.

WHY THE CLIENT HAS TO HOLD THIS. A loc carries a mapfunction number and nothing else - the
cache has no word for what the icon means, because the game never needed one: the minimap
draws the picture and the player works it out. A key that says "Bank" next to the bank icon
needs a name, and the only place a name exists is the content, where the loc that carries the
icon is called bank_store_icon.

MORE THAN ONE LOC CAN CARRY THE SAME ICON - a furnace with its own icon on it as well as the
bare icon loc placed beside one - so the name is taken from the one whose own name ends in
_icon, which is the loc that exists for no other reason. Where none does, the first by id
wins and is marked, because that is a name describing a thing rather than the icon.

THE TIDYING IS A SHORT LIST AND IT IS HERE WHERE YOU CAN SEE IT. Most names come straight out
of the content with the underscores opened up; the handful below are run-together words and two
of the content's own misspellings, which would otherwise be printed in the key as written.

    python3 tools/worldmap/make_icons.py [--check] [--content DIR]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'src/main/java/jagex2/client/worldmap/MapIconNames.java')
DEFAULT_CONTENT = os.path.join(os.path.dirname(ROOT), 'DeathPlateau-Content')

# The content's own name, where opening up the underscores is not enough. Two of these are its
# spellings rather than mine to choose: "jewlery" and "stagnent".
TIDIED = {
    'combattraining_store': 'Combat training',
    'dungeonentrance': 'Dungeon entrance',
    'jewlery_store': 'Jewellery store',
    'makeovermage': 'Make-over mage',
    'milk_churn': 'Dairy churn',
    'spinningwheel': 'Spinning wheel',
    'stagnent_water': 'Stagnant water',
    'transportation': 'Transportation',
}


def read(content):
    """(mapfunction -> loc name) out of every .loc the content has."""
    found = {}
    for root, _dirs, files in os.walk(content):
        for name in files:
            if not name.endswith('.loc'):
                continue
            block = None
            for line in open(os.path.join(root, name), encoding='utf-8', errors='replace'):
                line = line.strip()
                head = re.match(r'^\[(\w+)\]$', line)
                if head:
                    block = head.group(1)
                    continue
                m = re.match(r'^mapfunction=(\d+)$', line)
                if m and block:
                    found.setdefault(int(m.group(1)), []).append(block)
    return found


def label(names):
    """The name to print, out of every loc that carries this icon."""
    # The loc that exists only to be the icon is the one that names it.
    named = [n for n in names if n.endswith('_icon')]
    pick = sorted(named)[0] if named else sorted(names)[0]
    stem = pick[:-5] if pick.endswith('_icon') else pick
    if stem in TIDIED:
        return TIDIED[stem], not named
    return stem.replace('_', ' ').capitalize(), not named


def render(found):
    rows = []
    for func in sorted(found):
        text, borrowed = label(found[func])
        rows.append((func, text, borrowed))
    width = max(r[0] for r in rows) + 1
    out = []
    out.append('package jagex2.client.worldmap;')
    out.append('')
    out.append('/**')
    out.append(' * What each world map icon means.')
    out.append(' *')
    out.append(" * GENERATED by tools/worldmap/make_icons.py from the content's .loc files - do not")
    out.append(' * hand-edit; regenerate instead. MapWindowTest runs the generator again with --check')
    out.append(' * when the content repo is beside this one, so an icon added there and not here is a')
    out.append(' * failing test rather than a blank row in the key.')
    out.append(' *')
    out.append(' * WHY IT IS NOT IN THE CACHE. A loc carries a mapfunction number and nothing else: the')
    out.append(' * game never needed a word for it, because the minimap draws the picture and the player')
    out.append(' * works it out. The only place a name exists is the content, where the loc that carries')
    out.append(' * the bank icon is called bank_store_icon.')
    out.append(' */')
    out.append('public final class MapIconNames {')
    out.append('')
    out.append('\tprivate MapIconNames() {')
    out.append('\t}')
    out.append('')
    out.append('\t/** Indexed by mapfunction; "" for a number no loc carries. */')
    out.append('\tpublic static final String[] NAME = new String[%d];' % width)
    out.append('')
    out.append('\tstatic {')
    out.append('\t\tfor (int i = 0; i < NAME.length; i++) {')
    out.append('\t\t\tNAME[i] = "";')
    out.append('\t\t}')
    for func, text, borrowed in rows:
        tail = '    // no loc of its own; named after one that carries it' if borrowed else ''
        out.append('\t\tNAME[%d] = "%s";%s' % (func, text.replace('"', '\\"'), tail))
    out.append('\t}')
    out.append('')
    out.append('\t/** How many icons the content defines. */')
    out.append('\tpublic static int count() {')
    out.append('\t\tint n = 0;')
    out.append('\t\tfor (int i = 0; i < NAME.length; i++) {')
    out.append('\t\t\tif (NAME[i].length() > 0) {')
    out.append('\t\t\t\tn++;')
    out.append('\t\t\t}')
    out.append('\t\t}')
    out.append('\t\treturn n;')
    out.append('\t}')
    out.append('')
    out.append('\t/** What an icon means, or "" for one this table does not know. */')
    out.append('\tpublic static String name(int function) {')
    out.append('\t\treturn function < 0 || function >= NAME.length ? "" : NAME[function];')
    out.append('\t}')
    out.append('}')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if the file is out of date')
    ap.add_argument('--content', default=DEFAULT_CONTENT)
    ap.add_argument('--print', action='store_true', help='show the table rather than writing it')
    args = ap.parse_args()

    if not os.path.isdir(args.content):
        print('make_icons: no content repo at %s' % args.content)
        return 2                      # not a failure: the content is simply not here
    found = read(args.content)
    if not found:
        print('make_icons: read no icons at all - the patterns have gone stale')
        return 1
    if args.print:
        for func in sorted(found):
            text, borrowed = label(found[func])
            print('%2d  %-22s %s%s' % (func, text, ', '.join(sorted(found[func]))[:60],
                                       '   (borrowed)' if borrowed else ''))
        return 0
    want = render(found)
    have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else None
    if args.check:
        if have == want:
            print('make_icons: %s is up to date (%d icons)' % (os.path.basename(OUT), len(found)))
            return 0
        print('make_icons: %s is OUT OF DATE - run tools/worldmap/make_icons.py'
              % os.path.basename(OUT))
        return 1
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(want)
    print('make_icons: wrote %d icons to %s' % (len(found), os.path.basename(OUT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
