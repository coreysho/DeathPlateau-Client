#!/usr/bin/env python3
"""Generates MapLabels.java from the content's own maps/labels.txt.

WHERE THIS DATA ALREADY IS. The content ships a file of place names with world coordinates and
a rank, one per line, and until now nothing read it:

    =Lumbridge,3239,3233,1
    =Kingdom Of/Misthalin,3217,3321,2
    =Cooks/Guild,3137,3437,0

A slash is a line break, which is how a two-word place fits over a town without covering it.
The rank is how big a thing it is - 2 a kingdom or an island, 1 a town, 0 a landmark - and the
window uses it to decide what to show at which zoom, because a hundred and nineteen labels on
a view of the whole county is not a map, it is a list.

WHY THE COORDINATES ARE CHECKED AND NOT TRUSTED. A label is the one thing on this map with no
picture behind it: an icon that lands in the sea is obviously wrong, and a label that lands in
the sea just sits there looking like a place. So every one of them is held against the map
squares the content actually packs (maps/m<x>_<z>.jm2), and a label over ground the world does
not have fails this generator rather than shipping.

    python3 tools/worldmap/make_labels.py [--check] [--content DIR]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'src/main/java/jagex2/client/worldmap/MapLabels.java')
DEFAULT_CONTENT = os.path.join(os.path.dirname(ROOT), 'DeathPlateau-Content')

LINE = re.compile(r'^=([^,]+),(-?\d+),(-?\d+),(\d+)\s*$')
SQUARE = re.compile(r'^m(\d+)_(\d+)\.jm2$')

# A square is 64 tiles each way, and the content names its map files by square.
SQUARE_TILES = 64


def squares(content):
    """Every map square the content packs, as a set of (x, z)."""
    maps = os.path.join(content, 'maps')
    have = set()
    for name in os.listdir(maps):
        hit = SQUARE.match(name)
        if hit:
            have.add((int(hit.group(1)), int(hit.group(2))))
    return have


def read(content):
    """The labels, in file order, as dicts - or (None, complaint) if the file will not do."""
    path = os.path.join(content, 'maps/labels.txt')
    if not os.path.exists(path):
        return None, 'no maps/labels.txt in the content at %s' % content
    out = []
    with open(path, encoding='utf-8') as f:
        for number, raw in enumerate(f, 1):
            if not raw.strip() or raw.lstrip().startswith('//'):
                continue
            hit = LINE.match(raw.rstrip('\n'))
            if not hit:
                return None, 'maps/labels.txt line %d is not a label: %s' % (number, raw.strip())
            name, x, z, rank = hit.group(1), int(hit.group(2)), int(hit.group(3)), int(hit.group(4))
            out.append({'name': name, 'x': x, 'z': z, 'rank': rank})
    return out, None


def complain(labels, have):
    """Everything wrong with the set, as a list of lines. Empty when it is fit to generate."""
    bad = []
    seen = {}
    for label in labels:
        name = label['name']
        # THE SAME NAME TWICE IS FINE and the world is full of it: there are four sets of Ruins
        # and three Chaos Temples, and they are different places. The same name at the same
        # PLACE is the duplicate worth catching, which is a line pasted twice.
        where = (name, label['x'], label['z'])
        if where in seen:
            bad.append('%s at %d,%d is in the file twice' % where)
        seen[where] = 1
        if label['rank'] < 0 or label['rank'] > 2:
            bad.append('%s has rank %d, which is not 0, 1 or 2' % (name, label['rank']))
        at = (label['x'] // SQUARE_TILES, label['z'] // SQUARE_TILES)
        if at not in have:
            bad.append('%s is at %d,%d - square %d_%d, which the content does not pack'
                       % (name, label['x'], label['z'], at[0], at[1]))
    return bad


def render(labels):
    lines = []
    out = lines.append
    out('package jagex2.client.worldmap;')
    out('')
    out('/**')
    out(' * The names of places, over the map.')
    out(' *')
    out(' * GENERATED by tools/worldmap/make_labels.py from the content\'s maps/labels.txt - do')
    out(' * not hand-edit; add the place THERE and regenerate. MapWindowTest runs the generator')
    out(' * again with --check when the content repo is beside this one, so a place added there')
    out(' * and not here is a failing test rather than a label nobody can see.')
    out(' *')
    out(' * A SLASH IN A NAME IS A LINE BREAK, which is how "Kingdom Of/Misthalin" sits over a')
    out(' * kingdom without covering it. {@link #lines} is the only thing that knows that.')
    out(' *')
    out(' * RANK IS HOW BIG A THING IS - 2 a kingdom or an island, 1 a town, 0 a landmark - and')
    out(' * it is what decides which labels a zoom is worth showing. All of them at once, on a')
    out(' * view of the whole county, is not a map.')
    out(' */')
    out('public final class MapLabels {')
    out('')
    out('\tprivate MapLabels() {')
    out('\t}')
    out('')
    out('\t/** A kingdom or an island. */')
    out('\tpublic static final int RANK_REGION = 2;')
    out('')
    out('\t/** A town. */')
    out('\tpublic static final int RANK_TOWN = 1;')
    out('')
    out('\t/** Everything else with a name: a guild, a mine, a dungeon, a camp. */')
    out('\tpublic static final int RANK_PLACE = 0;')
    out('')
    out('\t/** The place names, slashes and all, in the order the content lists them. */')
    out('\tpublic static final String[] NAME = new String[] {')
    for label in labels:
        out('\t\t"%s",' % label['name'].replace('\\', '\\\\').replace('"', '\\"'))
    out('\t};')
    out('')
    for field, key in (('X', 'x'), ('Z', 'z'), ('RANK', 'rank')):
        out('\tpublic static final int[] %s = new int[] {' % field)
        row = []
        for label in labels:
            row.append(str(label[key]))
        for at in range(0, len(row), 12):
            out('\t\t' + ', '.join(row[at:at + 12]) + ',')
        out('\t};')
        out('')
    out('\t/**')
    out('\t * The character a name breaks its lines at, which is the content\'s own convention')
    out('\t * and not a path separator.')
    out('\t *')
    out('\t * NAMED ONCE because {@link #lines} walks the name twice - once to count the lines')
    out('\t * and once to cut them - and two loops that disagree about the character do not')
    out('\t * draw a wrong label, they walk off the end of the array they just sized.')
    out('\t */')
    out('\tpublic static final char BREAK = \'/\';')
    out('')
    out('\t/**')
    out('\t * A name split at its breaks, which is how it is drawn: one line under the next.')
    out('\t *')
    out('\t * A name with no break in it comes back as one line, which is most of them.')
    out('\t */')
    out('\tpublic static String[] lines(String name) {')
    out('\t\tint parts = 1;')
    out('\t\tfor (int at = 0; at < name.length(); at++) {')
    out('\t\t\tif (name.charAt(at) == BREAK) {')
    out('\t\t\t\tparts++;')
    out('\t\t\t}')
    out('\t\t}')
    out('\t\tString[] out = new String[parts];')
    out('\t\tint from = 0;')
    out('\t\tint which = 0;')
    out('\t\tfor (int at = 0; at <= name.length(); at++) {')
    out('\t\t\tif (at == name.length() || name.charAt(at) == BREAK) {')
    out('\t\t\t\tout[which++] = name.substring(from, at);')
    out('\t\t\t\tfrom = at + 1;')
    out('\t\t\t}')
    out('\t\t}')
    out('\t\treturn out;')
    out('\t}')
    out('}')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--content', default=DEFAULT_CONTENT)
    args = ap.parse_args()
    if not os.path.isdir(args.content):
        print('make_labels: no content repo at %s' % args.content)
        return 2
    labels, broken = read(args.content)
    if broken:
        print('make_labels: ' + broken)
        return 1
    if not labels:
        print('make_labels: read no labels at all - maps/labels.txt has gone empty')
        return 1
    bad = complain(labels, squares(args.content))
    if bad:
        for line in bad:
            print('make_labels: ' + line)
        return 1
    want = render(labels)
    ranks = [sum(1 for l in labels if l['rank'] == r) for r in (0, 1, 2)]
    said = ('%d labels (%d regions, %d towns, %d places), every one on a square the content packs'
            % (len(labels), ranks[2], ranks[1], ranks[0]))
    if args.check:
        got = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if got == want:
            print('make_labels: up to date (%s)' % said)
            return 0
        print('make_labels: MapLabels.java is stale - run tools/worldmap/make_labels.py')
        return 1
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(want)
    print('make_labels: wrote %s - %s' % (os.path.relpath(OUT, ROOT), said))
    return 0


if __name__ == '__main__':
    sys.exit(main())
