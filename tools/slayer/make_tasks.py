#!/usr/bin/env python3
"""Generates SlayerTasks.java from the content's task_name.enum and slayer.constant.

WHY THE CLIENT CARRIES THIS AT ALL. The server sends slayer_target, a small hand-assigned number
- 1 is monkeys, 2 goblins - and the name that goes with it lives in the content as
task_name.enum. A varp is an int, so the name cannot come over the wire, and the client's own
cache has never heard of slayer categories. Something has to hold the mapping, and the choice is
between a table here and a string squeezed through an interface component.

A TABLE, THEN, BUT GENERATED. Both halves of it are hand-assigned and stable - the numbers are
written out in slayer.constant rather than being a position in a list, the way loc ids are - so
this does not drift the way a packed id would. What it CAN do is fall behind when a task is
added, and that is what the check below is for: run with --check and it fails if the generated
file disagrees with the content, which is how SlayerTest notices.

    python3 tools/slayer/make_tasks.py [--check] [--content DIR]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'src/main/java/jagex2/client/plugin/builtin/SlayerTasks.java')
DEFAULT_CONTENT = os.path.join(os.path.dirname(ROOT), 'DeathPlateau-Content')


def read(content):
    """(id -> name) from the content, by crossing the constants with the name enum."""
    consts = {}
    cpath = os.path.join(content, 'scripts/skill_slayer/configs/slayer.constant')
    for line in open(cpath, encoding='utf-8'):
        m = re.match(r'\^(slayer_\w+)\s*=\s*(\d+)\s*$', line.strip())
        if m:
            consts[m.group(1)] = int(m.group(2))

    tasks = {}
    npath = os.path.join(content, 'scripts/skill_slayer/configs/task_name.enum')
    for line in open(npath, encoding='utf-8'):
        m = re.match(r'val=\^(\w+),(.+?)\s*$', line.strip())
        if not m:
            continue
        key, name = m.group(1), m.group(2)
        if key not in consts:
            continue
        # LAST WINS, as the enum itself resolves it: task_name repeats a few keys and the
        # server reads the last. Silently taking the first would disagree with the game.
        tasks[consts[key]] = name
    return tasks


def render(tasks):
    ids = sorted(tasks)
    width = max(ids) + 1
    lines = []
    lines.append('package jagex2.client.plugin.builtin;')
    lines.append('')
    lines.append('/**')
    lines.append(' * What each slayer task id is called.')
    lines.append(' *')
    lines.append(' * GENERATED by tools/slayer/make_tasks.py from the content\'s task_name.enum and')
    lines.append(' * slayer.constant - do not hand-edit; regenerate instead. SlayerTest runs the generator')
    lines.append(' * again with --check when the content repo is beside this one, so a task added there and')
    lines.append(' * not here is a failing test rather than a blank row.')
    lines.append(' *')
    lines.append(' * WHY THE CLIENT HAS TO HOLD THIS. The server sends slayer_target, a hand-assigned number,')
    lines.append(' * and a varp is an int - the name cannot come over the wire, and this cache has never')
    lines.append(' * heard of a slayer category. The numbers are written out in slayer.constant rather than')
    lines.append(' * being a position in a list, so unlike a loc id they do not move underneath this.')
    lines.append(' */')
    lines.append('public final class SlayerTasks {')
    lines.append('')
    lines.append('\tprivate SlayerTasks() {')
    lines.append('\t}')
    lines.append('')
    lines.append('\t/** Indexed by slayer_target; "" for a number no task uses. */')
    lines.append('\tstatic final String[] NAME = new String[%d];' % width)
    lines.append('')
    lines.append('\tstatic {')
    lines.append('\t\tfor (int i = 0; i < NAME.length; i++) {')
    lines.append('\t\t\tNAME[i] = "";')
    lines.append('\t\t}')
    for i in ids:
        lines.append('\t\tNAME[%d] = "%s";' % (i, tasks[i].replace('\\', '\\\\').replace('"', '\\"')))
    lines.append('\t}')
    lines.append('')
    lines.append('\t/** How many tasks the content defines. */')
    lines.append('\tpublic static int count() {')
    lines.append('\t\tint n = 0;')
    lines.append('\t\tfor (int i = 0; i < NAME.length; i++) {')
    lines.append('\t\t\tif (NAME[i].length() > 0) {')
    lines.append('\t\t\t\tn++;')
    lines.append('\t\t\t}')
    lines.append('\t\t}')
    lines.append('\t\treturn n;')
    lines.append('\t}')
    lines.append('')
    lines.append('\t/** What a task id is called, or "" for one this table does not know. */')
    lines.append('\tpublic static String name(int target) {')
    lines.append('\t\treturn target < 0 || target >= NAME.length ? "" : NAME[target];')
    lines.append('\t}')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true', help='fail if the file is out of date')
    ap.add_argument('--content', default=DEFAULT_CONTENT)
    args = ap.parse_args()

    if not os.path.isdir(args.content):
        print('make_tasks: no content repo at %s' % args.content)
        return 2                      # not a failure: the content is simply not here
    tasks = read(args.content)
    if not tasks:
        print('make_tasks: read no tasks at all - the patterns have gone stale')
        return 1
    want = render(tasks)
    if args.check:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if have == want:
            print('make_tasks: up to date (%d tasks)' % len(tasks))
            return 0
        print('make_tasks: OUT OF DATE - %d tasks in the content, regenerate with' % len(tasks))
        print('  python3 tools/slayer/make_tasks.py')
        return 1
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(want)
    print('make_tasks: wrote %d tasks to %s' % (len(tasks), os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
