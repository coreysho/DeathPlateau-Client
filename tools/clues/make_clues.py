#!/usr/bin/env python3
"""Generates ClueSteps.java from the content's clue objs.

WHERE THIS DATA ALREADY IS. Every clue step in this game is its own object - 102 of them - and
each carries what it says as a param:

    param=trail_desc,Search the chest in the|Duke of Lumbridge's bedroom.
    param=trail_coord,0_49_52_41_32

So the content already holds, per step, the text and (for the 38 coordinate clues) the place.
It is structured data rather than logic scattered through scripts, which is what makes a helper
possible at all - and it means no server change: the client can already see which clue is in the
inventory, and this table says what that clue wants.

THE IDS COME FROM pack/obj.pack, which is a file of explicit assignments rather than an order
things happen to be packed in, so they are stable in the way a loc id is not.

    python3 tools/clues/make_clues.py [--check] [--content DIR]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(ROOT, 'src/main/java/jagex2/client/plugin/builtin/ClueSteps.java')
DEFAULT_CONTENT = os.path.join(os.path.dirname(ROOT), 'DeathPlateau-Content')


def coord(raw):
    """level_squareX_squareZ_localX_localZ -> (level, absolute x, absolute z)."""
    parts = raw.split('_')
    if len(parts) != 5:
        return None
    try:
        level, sx, sz, lx, lz = (int(p) for p in parts)
    except ValueError:
        return None
    return level, sx * 64 + lx, sz * 64 + lz


def read(content):
    ids = {}
    for line in open(os.path.join(content, 'pack/obj.pack'), encoding='utf-8'):
        if '=' in line:
            num, name = line.strip().split('=', 1)
            ids[name] = int(num)

    steps = {}
    cur = None
    desc = None
    place = None
    path = os.path.join(content, 'scripts/_unpack/377/all.obj')

    def flush():
        # EITHER IS ENOUGH. A map clue carries a coordinate and no trail_desc, because its text
        # is a picture - the five of them were dropped by a version of this that insisted on
        # the words, and they are exactly the steps a helper is most use for.
        if cur is not None and (desc is not None or place is not None) and cur in ids:
            steps[ids[cur]] = (cur, desc or '', place)

    for line in open(path, encoding='utf-8', errors='replace'):
        line = line.rstrip('\n')
        if line.startswith('['):
            flush()
            cur = line.strip('[]')
            desc = None
            place = None
        elif line.startswith('param=trail_desc,'):
            desc = line.split(',', 1)[1]
        elif line.startswith('param=trail_coord,'):
            place = coord(line.split(',', 1)[1].strip())
    flush()
    return steps


def java(text):
    return text.replace('\\', '\\\\').replace('"', '\\"')


def render(steps):
    ids = sorted(steps)
    withcoord = sum(1 for i in ids if steps[i][2])
    out = []
    out.append('package jagex2.client.plugin.builtin;')
    out.append('')
    out.append('/**')
    out.append(' * What every clue step says, and where the coordinate ones point.')
    out.append(' *')
    out.append(" * GENERATED by tools/clues/make_clues.py from the content's clue objs - do not hand-edit;")
    out.append(' * regenerate instead. ClueTest runs the generator again with --check when the content repo')
    out.append(' * is beside this one, so a clue added there and not here is a failing test rather than a')
    out.append(' * scroll the page has nothing to say about.')
    out.append(' *')
    out.append(' * Each step is its own object and carries its own text, so none of this is invented or')
    out.append(" * guessed: trail_desc is the clue's own words and trail_coord is its own dig spot, both")
    out.append(' * read straight out of the content. Keyed by obj id, from the explicit assignments in')
    out.append(' * pack/obj.pack.')
    out.append(' *')
    out.append(' * %d steps, %d of them with a place to dig. A step with no words is a map clue,' % (len(ids), withcoord))
    out.append(' * whose text is a picture the client is handed only when the scroll is opened.')
    out.append(' */')
    out.append('public final class ClueSteps {')
    out.append('')
    out.append('\tprivate ClueSteps() {')
    out.append('\t}')
    out.append('')
    out.append('\t/** Clue obj ids, ascending, so a lookup can stop early. */')
    out.append('\tstatic final int[] ID = {')
    for i in range(0, len(ids), 10):
        out.append('\t\t' + ', '.join(str(x) for x in ids[i:i + 10]) + ',')
    out.append('\t};')
    out.append('')
    out.append("\t/** What each one says. A '|' is where the game breaks the line. */")
    out.append('\tstatic final String[] TEXT = {')
    for i in ids:
        out.append('\t\t"%s",' % java(steps[i][1]))
    out.append('\t};')
    out.append('')
    out.append('\t/** Where to dig, as level, x, z - or -1, -1, -1 for a step that is not a coordinate. */')
    out.append('\tstatic final int[] LEVEL = {')
    out.append('\t\t' + ', '.join(str(steps[i][2][0] if steps[i][2] else -1) for i in ids) + '')
    out.append('\t};')
    out.append('')
    out.append('\tstatic final int[] X = {')
    out.append('\t\t' + ', '.join(str(steps[i][2][1] if steps[i][2] else -1) for i in ids))
    out.append('\t};')
    out.append('')
    out.append('\tstatic final int[] Z = {')
    out.append('\t\t' + ', '.join(str(steps[i][2][2] if steps[i][2] else -1) for i in ids))
    out.append('\t};')
    out.append('')
    out.append('\t/** Where this obj sits in the arrays above, or -1 for an obj that is not a clue. */')
    out.append('\tpublic static int indexOf(int objId) {')
    out.append('\t\tint low = 0;')
    out.append('\t\tint high = ID.length - 1;')
    out.append('\t\twhile (low <= high) {')
    out.append('\t\t\tint mid = (low + high) >>> 1;')
    out.append('\t\t\tif (ID[mid] == objId) {')
    out.append('\t\t\t\treturn mid;')
    out.append('\t\t\t}')
    out.append('\t\t\tif (ID[mid] < objId) {')
    out.append('\t\t\t\tlow = mid + 1;')
    out.append('\t\t\t} else {')
    out.append('\t\t\t\thigh = mid - 1;')
    out.append('\t\t\t}')
    out.append('\t\t}')
    out.append('\t\treturn -1;')
    out.append('\t}')
    out.append('')
    out.append('\t/** How many steps this table knows. */')
    out.append('\tpublic static int count() {')
    out.append('\t\treturn ID.length;')
    out.append('\t}')
    out.append('}')
    return '\n'.join(out) + '\n'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    ap.add_argument('--content', default=DEFAULT_CONTENT)
    args = ap.parse_args()
    if not os.path.isdir(args.content):
        print('make_clues: no content repo at %s' % args.content)
        return 2
    steps = read(args.content)
    if not steps:
        print('make_clues: read no clue steps at all - the patterns have gone stale')
        return 1
    want = render(steps)
    if args.check:
        have = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if have == want:
            print('make_clues: up to date (%d steps)' % len(steps))
            return 0
        print('make_clues: OUT OF DATE - %d steps in the content, regenerate with' % len(steps))
        print('  python3 tools/clues/make_clues.py')
        return 1
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(want)
    print('make_clues: wrote %d steps to %s' % (len(steps), os.path.relpath(OUT, ROOT)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
